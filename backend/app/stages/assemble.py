"""Render a composed document plan (title + sections of typed blocks) to
Markdown, DOCX, and PDF. Pure rendering, no LLM calls -- placement was already
decided by compose.py; this just draws it.
"""

import shutil
from pathlib import Path
from xml.sax.saxutils import escape

from PIL import Image as PILImage


def _caption(block: dict, meta: dict) -> str:
    # compose.py's LLM sometimes leaves an image/table block's caption empty
    # despite the placement decision -- fall back to the classify-step caption,
    # which always exists, rather than rendering an empty caption.
    return block.get("caption") or meta.get("caption", "")


def render_table_markdown(table: dict, caption: str = "") -> str:
    """Renders one table's headers/rows (+ optional caption) as a standalone
    markdown table. Shared by render_markdown's per-block rendering and
    routes/review.py's single-table export, so there's exactly one place that
    knows how a table becomes markdown."""
    lines = ["| " + " | ".join(table["headers"]) + " |"]
    lines.append("| " + " | ".join("---" for _ in table["headers"]) + " |")
    for row in table["rows"]:
        lines.append("| " + " | ".join(str(c) for c in row) + " |")
    if caption:
        lines.append("")
        lines.append(f"*{caption}*")
    return "\n".join(lines)


def render_markdown(title: str, sections: list[dict], images_by_id: dict, tables_by_id: dict, output_dir: Path) -> Path:
    images_dir = output_dir / "images"
    images_dir.mkdir(parents=True, exist_ok=True)

    lines = [f"# {title}", ""]
    for section in sections:
        lines.append(f"## {section['heading']}")
        lines.append("")
        for block in section["blocks"]:
            if block["type"] == "paragraph":
                if block["text"]:
                    lines.append(block["text"])
                    lines.append("")
            elif block["type"] == "image":
                image = images_by_id.get(block["ref"])
                if not image:
                    continue
                caption = _caption(block, image)
                image_name = f"{image['id']}.jpg"
                shutil.copy(image["path"], images_dir / image_name)
                lines.append(f"![{caption}](images/{image_name})")
                lines.append(f"*{caption}*")
                lines.append("")
            elif block["type"] == "table":
                table = tables_by_id.get(block["ref"])
                if not table:
                    continue
                lines.append(render_table_markdown(table, _caption(block, table)))
                lines.append("")

    output_path = output_dir / "document.md"
    output_path.write_text("\n".join(lines))
    return output_path


FONTS_DIR = Path(__file__).resolve().parent.parent / "assets" / "fonts"

# Same light-mode brand values as the web app (marketing/src/styles/tokens.css).
# Exported documents always use the light palette -- there's no "dark mode"
# for something meant to be printed or handed to someone else.
BRAND = {
    "ink": "#14120f",
    "ink_soft": "#56514a",
    "paper": "#ffffff",
    "paper_shade": "#f2f0ec",
    "line": "#dedbd4",
    "accent": "#c81e3a",
    "accent_ink": "#ffffff",
}


def _hex(color: str) -> str:
    return color.lstrip("#").upper()


def _fit_dimensions(w: int, h: int, max_width_in: float, max_height_in: float) -> tuple[float, float]:
    """Scales to fit within a width AND height cap (not just width), so a
    tall portrait screenshot can't run off the bottom of the page."""
    width_in = max_width_in
    height_in = width_in * (h / w)
    if height_in > max_height_in:
        height_in = max_height_in
        width_in = height_in * (w / h)
    return width_in, height_in


