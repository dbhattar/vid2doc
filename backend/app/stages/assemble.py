_PDF_FONTS_REGISTERED = False


def _register_pdf_fonts() -> None:
    global _PDF_FONTS_REGISTERED
    if _PDF_FONTS_REGISTERED:
        return
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    pdfmetrics.registerFont(TTFont("Fraunces-Bold", str(FONTS_DIR / "fraunces" / "Fraunces-900.ttf")))
    pdfmetrics.registerFont(TTFont("Fraunces-SemiBold", str(FONTS_DIR / "fraunces" / "Fraunces-600.ttf")))
    pdfmetrics.registerFont(TTFont("Fraunces-Italic", str(FONTS_DIR / "fraunces" / "Fraunces-500Italic.ttf")))
    pdfmetrics.registerFont(TTFont("PlexMono", str(FONTS_DIR / "ibm-plex-mono" / "IBMPlexMono-400.ttf")))
    pdfmetrics.registerFont(TTFont("PlexMono-Medium", str(FONTS_DIR / "ibm-plex-mono" / "IBMPlexMono-500.ttf")))
    _PDF_FONTS_REGISTERED = True


def _pdf_styles() -> dict:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet

    ink = colors.HexColor(BRAND["ink"])
    ink_soft = colors.HexColor(BRAND["ink_soft"])

    body = getSampleStyleSheet()["BodyText"]
    body.textColor = ink
    body.fontSize = 10.5
    body.leading = 15

    return {
        "cover_title": ParagraphStyle(
            "CoverTitle", fontName="Fraunces-Bold", fontSize=34, leading=38, textColor=ink, alignment=TA_CENTER
        ),
        "cover_subtitle": ParagraphStyle(
            "CoverSubtitle",
            fontName="Fraunces-Italic",
            fontSize=13,
            leading=18,
            textColor=ink_soft,
            alignment=TA_CENTER,
            spaceBefore=10,
        ),
        # Name matched against in _ReportDocTemplate.afterFlowable below to
        # decide which paragraphs earn a TOC entry -- keep the two in sync.
        "heading1": ParagraphStyle(
            "SectionHeading", fontName="Fraunces-SemiBold", fontSize=17, leading=21, textColor=ink, spaceBefore=18, spaceAfter=10
        ),
        "body": body,
        "caption": ParagraphStyle("Caption", fontName="PlexMono", fontSize=8.5, leading=12, textColor=ink_soft, spaceAfter=12),
        "toc_heading": ParagraphStyle("TOCHeading", fontName="Fraunces-SemiBold", fontSize=17, leading=21, textColor=ink, spaceAfter=12),
        "toc_entry": ParagraphStyle("TOCEntry", fontName="PlexMono", fontSize=10, leading=16, textColor=ink),
    }


def _pdf_page_furniture(canvas, doc, title: str) -> None:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import letter
    from reportlab.lib.units import inch

    canvas.saveState()
    canvas.setStrokeColor(colors.HexColor(BRAND["line"]))
    canvas.setLineWidth(0.75)
    canvas.line(0.75 * inch, 0.65 * inch, letter[0] - 0.75 * inch, 0.65 * inch)

    canvas.setFont("PlexMono", 8.5)
    canvas.setFillColor(colors.HexColor(BRAND["ink_soft"]))
    canvas.drawString(0.75 * inch, 0.45 * inch, title[:60])
    canvas.drawRightString(letter[0] - 0.75 * inch, 0.45 * inch, f"Page {doc.page}")
    canvas.restoreState()


def _build_pdf_doc_template(output_path: Path, title: str):
    from functools import partial

    from reportlab.lib.pagesizes import letter
    from reportlab.lib.units import inch
    from reportlab.platypus import BaseDocTemplate, Frame, PageTemplate, Paragraph

    class _ReportDocTemplate(BaseDocTemplate):
        def afterFlowable(self, flowable):
            # Registers each section heading's resolved page number for the
            # TOC's second build pass, and adds a PDF outline/bookmark entry
            # as a bonus -- a documented reportlab pattern (multiBuild +
            # TOCEntry notifications), not a hack.
            if isinstance(flowable, Paragraph) and flowable.style.name == "SectionHeading":
                text = flowable.getPlainText()
                self.notify("TOCEntry", (0, text, self.page))
                key = f"section-{self.page}-{id(flowable)}"
                self.canv.bookmarkPage(key)
                self.canv.addOutlineEntry(text, key, level=0)

    frame = Frame(0.75 * inch, 0.9 * inch, letter[0] - 1.5 * inch, letter[1] - 1.8 * inch, id="normal")
    template = PageTemplate(id="all", frames=[frame], onPage=partial(_pdf_page_furniture, title=title))
    return _ReportDocTemplate(str(output_path), pagesize=letter, pageTemplates=[template])


def _pdf_image_dimensions(path: Path, max_width_in: float = 4.5, max_height_in: float = 6.0):
    from reportlab.lib.units import inch

    with PILImage.open(path) as img:
        w, h = img.size
    width_in, height_in = _fit_dimensions(w, h, max_width_in, max_height_in)
    return width_in * inch, height_in * inch


def render_pdf(title: str, sections: list[dict], images_by_id: dict, tables_by_id: dict, output_path: Path) -> Path:
    from datetime import datetime

    from reportlab.lib import colors
    from reportlab.platypus import Image as RLImage
    from reportlab.platypus import PageBreak, Paragraph, Spacer, Table, TableStyle
    from reportlab.platypus.tableofcontents import TableOfContents

    _register_pdf_fonts()
    styles = _pdf_styles()
    doc = _build_pdf_doc_template(output_path, title)

    story = [
        Spacer(1, 220),
        Paragraph(escape(title), styles["cover_title"]),
        Paragraph(f"Generated by Framewrite &middot; {datetime.now().strftime('%B %d, %Y')}", styles["cover_subtitle"]),
        PageBreak(),
    ]

    # Same >1-section threshold as the DOCX renderer -- a single-section
    # document doesn't need a table of contents pointing at itself.
    if len(sections) > 1:
        toc = TableOfContents()
        toc.levelStyles = [styles["toc_entry"]]
        story.append(Paragraph("Contents", styles["toc_heading"]))
        story.append(toc)
        story.append(PageBreak())

    for section in sections:
        story.append(Paragraph(escape(section["heading"]), styles["heading1"]))
        for block in section["blocks"]:
            if block["type"] == "paragraph":
                if block["text"]:
                    story.append(Paragraph(escape(block["text"]), styles["body"]))
                    story.append(Spacer(1, 6))
            elif block["type"] == "image":
                image = images_by_id.get(block["ref"])
                if not image:
                    continue
                width, height = _pdf_image_dimensions(Path(image["path"]))
                img = RLImage(image["path"], width=width, height=height)
                img.hAlign = "CENTER"
                story.append(img)
                story.append(Paragraph(escape(_caption(block, image)), styles["caption"]))
            elif block["type"] == "table":
                table_data = tables_by_id.get(block["ref"])
                if not table_data:
                    continue
                header = [str(h).upper() for h in table_data["headers"]]
                rows = [header] + table_data["rows"]
                t = Table(rows)
                t.hAlign = "CENTER"
                t.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(BRAND["ink"])),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor(BRAND["paper"])),
                    ("FONTNAME", (0, 0), (-1, 0), "PlexMono-Medium"),
                    ("FONTSIZE", (0, 0), (-1, -1), 9),
                    ("TEXTCOLOR", (0, 1), (-1, -1), colors.HexColor(BRAND["ink"])),
                    ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor(BRAND["paper"])),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor(BRAND["line"])),
                    ("TOPPADDING", (0, 0), (-1, -1), 5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ]))
                story.append(t)
                story.append(Paragraph(escape(_caption(block, table_data)), styles["caption"]))

    doc.multiBuild(story)
    return output_path
