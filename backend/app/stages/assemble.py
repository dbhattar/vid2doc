def _docx_style_headings(doc) -> None:
    from docx.shared import Pt, RGBColor

    heading1 = doc.styles["Heading 1"]
    heading1.font.name = "Fraunces"
    heading1.font.size = Pt(18)
    heading1.font.bold = True
    heading1.font.color.rgb = RGBColor.from_string(_hex(BRAND["ink"]))
    heading1.paragraph_format.space_before = Pt(18)
    heading1.paragraph_format.space_after = Pt(10)


def _docx_add_cover_page(doc, title: str) -> None:
    from datetime import datetime

    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Pt, RGBColor

    for _ in range(6):
        doc.add_paragraph()

    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title_p.add_run(title)
    title_run.font.name = "Fraunces"
    title_run.font.size = Pt(32)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor.from_string(_hex(BRAND["ink"]))

    subtitle_p = doc.add_paragraph()
    subtitle_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle_run = subtitle_p.add_run(f"Generated by Framewrite · {datetime.now().strftime('%B %d, %Y')}")
    subtitle_run.font.name = "IBM Plex Mono"
    subtitle_run.font.size = Pt(11)
    subtitle_run.italic = True
    subtitle_run.font.color.rgb = RGBColor.from_string(_hex(BRAND["ink_soft"]))

    doc.add_page_break()


def _docx_add_toc(doc) -> None:
    """Inserts a real, clickable TOC field (`{ TOC \\o "1-3" \\h \\z \\u }`) via
    the standard raw-oxml field-code recipe -- python-docx has no high-level
    API for this, but Word auto-populates it from the Heading 1 styles
    already in use once the field is updated (automatically on open, or via
    right-click > Update Field, hence the placeholder text below)."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Pt, RGBColor

    heading_p = doc.add_paragraph()
    heading_run = heading_p.add_run("Contents")
    heading_run.font.name = "Fraunces"
    heading_run.font.size = Pt(16)
    heading_run.font.bold = True
    heading_run.font.color.rgb = RGBColor.from_string(_hex(BRAND["ink"]))

    toc_p = doc.add_paragraph()

    def _field_run(text: str | None = None):
        run = toc_p.add_run(text or "")
        run.font.name = "IBM Plex Mono"
        run.font.size = Pt(10.5)
        return run

    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    _field_run()._r.append(begin)

    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = 'TOC \\o "1-3" \\h \\z \\u'
    _field_run()._r.append(instr)

    separate = OxmlElement("w:fldChar")
    separate.set(qn("w:fldCharType"), "separate")
    _field_run()._r.append(separate)

    _field_run("Right-click and choose “Update Field” to generate the table of contents.")

    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    _field_run()._r.append(end)

    doc.add_page_break()


def _docx_add_caption(doc, text: str):
    from docx.shared import Pt, RGBColor

    p = doc.add_paragraph()
    run = p.add_run(text)
    run.italic = True
    run.font.name = "IBM Plex Mono"
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor.from_string(_hex(BRAND["ink_soft"]))
    return p


def _docx_shade_cell(cell, hex_color: str) -> None:
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn

    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    cell._tc.get_or_add_tcPr().append(shd)


def _docx_set_table_borders(table, hex_color: str) -> None:
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn

    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:color"), hex_color)
        borders.append(el)
    table._tbl.tblPr.append(borders)


def _docx_format_header_row(table, ncols: int) -> None:
    from docx.shared import Pt, RGBColor

    for c in range(ncols):
        cell = table.cell(0, c)
        _docx_shade_cell(cell, _hex(BRAND["ink"]))
        for paragraph in cell.paragraphs:
            for run in paragraph.runs:
                run.font.bold = True
                run.font.name = "IBM Plex Mono"
                run.font.size = Pt(9)
                run.font.color.rgb = RGBColor.from_string(_hex(BRAND["paper"]))


def _docx_add_page_number_field(paragraph) -> None:
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Pt, RGBColor

    def _run(text: str | None = None):
        run = paragraph.add_run(text or "")
        run.font.name = "IBM Plex Mono"
        run.font.size = Pt(8.5)
        run.font.color.rgb = RGBColor.from_string(_hex(BRAND["ink_soft"]))
        return run

    _run("Page ")

    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    _run()._r.append(begin)

    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = "PAGE"
    _run()._r.append(instr)

    separate = OxmlElement("w:fldChar")
    separate.set(qn("w:fldCharType"), "separate")
    _run()._r.append(separate)

    _run("1")

    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    _run()._r.append(end)


def _docx_add_footer(doc) -> None:
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    footer = doc.sections[0].footer
    paragraph = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    _docx_add_page_number_field(paragraph)


def _docx_image_dimensions(path: Path, max_width_in: float = 5.5, max_height_in: float = 7.0):
    from docx.shared import Inches

    with PILImage.open(path) as img:
        w, h = img.size
    width_in, height_in = _fit_dimensions(w, h, max_width_in, max_height_in)
    return Inches(width_in), Inches(height_in)


def render_docx(title: str, sections: list[dict], images_by_id: dict, tables_by_id: dict, output_path: Path) -> Path:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    doc = Document()
    _docx_style_headings(doc)
    _docx_add_cover_page(doc, title)

    # A TOC only earns its keep once there's more than one section to jump
    # between -- for a single-section document it would just repeat the one
    # heading already visible on the next page.
    if len(sections) > 1:
        _docx_add_toc(doc)

    for section in sections:
        doc.add_heading(section["heading"], level=1)
        for block in section["blocks"]:
            if block["type"] == "paragraph":
                if block["text"]:
                    doc.add_paragraph(block["text"])
            elif block["type"] == "image":
                image = images_by_id.get(block["ref"])
                if not image:
                    continue
                width, height = _docx_image_dimensions(Path(image["path"]))
                doc.add_picture(image["path"], width=width, height=height)
                doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
                caption_p = _docx_add_caption(doc, _caption(block, image))
                caption_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            elif block["type"] == "table":
                table_data = tables_by_id.get(block["ref"])
                if not table_data:
                    continue
                header = [str(h).upper() for h in table_data["headers"]]
                rows = [header] + table_data["rows"]
                table = doc.add_table(rows=len(rows), cols=len(header))
                _docx_set_table_borders(table, _hex(BRAND["line"]))
                for r, row in enumerate(rows):
                    for c, val in enumerate(row):
                        table.cell(r, c).text = str(val)
                _docx_format_header_row(table, len(header))
                _docx_add_caption(doc, _caption(block, table_data))

    _docx_add_footer(doc)
    doc.save(output_path)
    return output_path


